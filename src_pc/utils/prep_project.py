#!/usr/bin/env python3
"""
src_pc/utils/prep_project.py

Run-once project setup: rebuilds the camera yaml and sequence yamls from
src_pc/configs/project_settings.py. Re-run whenever a DATASET_* / IMAGE_* /
CAMERA_* / ORB_* value changes there.

Layout depends on DATASET_GRAYSCALE:
  False (default): RGB,  frames -> image_2/(left) image_3/(right), is_color=True,  Camera.RGB=1
  True:            gray, frames -> image_0/(left) image_1/(right), is_color=False, Camera.RGB=0

Camera yaml is generated from calibration/perspective.txt, scaled to
IMAGE_WIDTH (aspect ratio preserved).

Expects raw layout:
  dataset/raw/kitti360/  calibration/  data_2d_test_slam/  data_poses/

Usage:
    python3 src_pc/utils/prep_project.py
"""

import sys
import shutil
import yaml
import numpy as np
from pathlib import Path

PC_ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(PC_ROOT))

from src_pc.configs.project_settings import (
    TRAJ_FORMAT, NUM_FEATURES, MAX_STEREO_DEPTH,
    DATASET_GRAYSCALE, IMAGE_WIDTH, CAMERA_FPS,
    ORB_SCALE_FACTOR, ORB_NUM_LEVELS, ORB_INI_TH_FAST, ORB_MIN_TH_FAST,
)
from src_pc.utils.paths import (
    PROCESSED_CALIB, PROCESSED_IMAGES, PROCESSED_POSES,
    KITTI_BASE_PATH, DOCS_DATASET, CONFIGS_SEQUENCES, RESULTS,
)
from src_pc.utils.dataset_helper_functions import process_sequence
from src_pc.utils.printing_helper_functions import (
    write_sequence_stats, write_dataset_summary,
    plot_trajectory, plot_dataset_overview,
)

RAW_ROOT      = PC_ROOT / "dataset" / "raw"
RAW_KITTI     = RAW_ROOT / "kitti360"
RAW_KITTI_IMG = RAW_KITTI / "data_2d_test_slam"
RAW_KITTI_POS = RAW_KITTI / "data_poses"
RAW_KITTI_CAL = RAW_KITTI / "calibration"

CONFIGS_DIR = PC_ROOT / "src_pc" / "configs"
CAM_KITTI   = CONFIGS_DIR / "cam_kitti360.yaml"


# KITTI-360 camera yaml  (generated from perspective.txt) ----------------------------------

def _read_kitti_intrinsics(perspective_txt: Path) -> dict | None:
    """
    Pull the intrinsics out of KITTI-360's perspective.txt.
      S_rect_00  → original width, height
      P_rect_00  → fx, fy, cx, cy
      P_rect_01  → bf = |Tx| = baseline × fx
    """
    if not perspective_txt.is_file():
        print(f"  [!] perspective.txt not found: {perspective_txt}")
        return None
    try:
        vals = {}
        with open(perspective_txt) as f:
            for line in f:
                if line.startswith("S_rect_00"):
                    parts = line.split(":")[1].split()
                    vals["w_orig"] = int(float(parts[0]))
                    vals["h_orig"] = int(float(parts[1]))
                elif line.startswith("P_rect_00"):
                    P = np.array(line.split(":")[1].split(), dtype=float).reshape(3, 4)
                    vals["fx"] = float(P[0, 0])
                    vals["fy"] = float(P[1, 1])
                    vals["cx"] = float(P[0, 2])
                    vals["cy"] = float(P[1, 2])
                elif line.startswith("P_rect_01"):
                    P1 = np.array(line.split(":")[1].split(), dtype=float).reshape(3, 4)
                    vals["bf"] = abs(float(P1[0, 3]))
        missing = [k for k in ("w_orig", "h_orig", "fx", "fy", "cx", "cy", "bf") if k not in vals]
        if missing:
            print(f"  [!] perspective.txt missing: {missing}")
            return None
        return vals
    except Exception as e:
        print(f"  [!] perspective.txt parse error: {e}")
        return None


def _write_cam_kitti_yaml(cam_path: Path, intr: dict, target_width: int | None,
                          is_grayscale: bool) -> None:
    """
    Write cam_kitti360.yaml with the intrinsics scaled to target_width (aspect
    ratio kept). Always rewritten from scratch so config changes actually take.
    """
    w_orig = intr["w_orig"]
    eff_width = w_orig if target_width is None else int(target_width)
    scale  = eff_width / w_orig
    h_new  = round(intr["h_orig"] * scale)
    fx_new = intr["fx"] * scale
    fy_new = intr["fy"] * scale
    cx_new = intr["cx"] * scale
    cy_new = intr["cy"] * scale
    baseline = intr["bf"] / intr["fx"]   # metres — physical, scale-invariant
    bf_new   = baseline * fx_new
    rgb_flag = 0 if is_grayscale else 1
    colour   = "grayscale" if is_grayscale else "RGB"

    lines = [
        f"# Camera Calibration — KITTI-360  ({eff_width}×{h_new}, {colour})",
        "# Full original resolution" if scale == 1.0 else f"# Scaled from {w_orig}x{intr['h_orig']} (scale={scale:.6f})",
        "# Auto-generated by prep_project.py from calibration/perspective.txt",
        "# DO NOT edit by hand — change src_pc/configs/project_settings.py and re-run prep_project.py",
        "",
        f"Camera.fx: {fx_new:.6f}",
        f"Camera.fy: {fy_new:.6f}",
        f"Camera.cx: {cx_new:.6f}",
        f"Camera.cy: {cy_new:.6f}",
        "",
        "Camera.k1: 0.0",
        "Camera.k2: 0.0",
        "Camera.p1: 0.0",
        "Camera.p2: 0.0",
        "",
        f"Camera.width:  {eff_width}",
        f"Camera.height: {h_new}",
        f"Camera.fps: {float(CAMERA_FPS)}",
        "",
        f"Camera.RGB: {rgb_flag}",
        "",
        f"Camera.bf: {bf_new:.3f}",
        f"ThDepth: {float(MAX_STEREO_DEPTH):.1f}",
        "",
        f"ORBextractor.nFeatures:   {NUM_FEATURES}",
        f"ORBextractor.scaleFactor: {ORB_SCALE_FACTOR}",
        f"ORBextractor.nLevels:     {ORB_NUM_LEVELS}",
        f"ORBextractor.iniThFAST:   {ORB_INI_TH_FAST}",
        f"ORBextractor.minThFAST:   {ORB_MIN_TH_FAST}",
    ]
    cam_path.parent.mkdir(parents=True, exist_ok=True)
    with open(cam_path, "w") as f:
        f.write("\n".join(lines) + "\n")
    print(f"  - Written {cam_path.name}  "
          f"({eff_width}×{h_new}, {colour}, RGB={rgb_flag}, bf={bf_new:.1f}, "
          f"ThDepth={MAX_STEREO_DEPTH}m, features={NUM_FEATURES})")


# pySLAM sequence yaml ---------------------------------------------------------------------

_SLAM_IO = {
    "DATASET":    {"type": "KITTI_DATASET"},
    "SAVE_TRAJECTORY": {
        "save_trajectory": True,
        "format_type":     TRAJ_FORMAT,
        "output_folder":   str(RESULTS),
    },
    "SYSTEM_STATE": {
        "load_state":  False,
        "folder_path": str(RESULTS.parent / "slam_state"),
    },
    "GLOBAL_PARAMETERS": {
        "kLogsFolder": str(RESULTS.parent / "logs"),
    },
}


def _generate_sequence_config(seq: dict, cam_config: Path) -> Path:
    cfg = {
        **_SLAM_IO,
        "KITTI_DATASET": {
            "type":        "kitti",
            "sensor_type": "stereo",
            "base_path":   str(KITTI_BASE_PATH),
            "name":        f"{seq['test']}/{seq['drive']}",
            "settings":    str(cam_config),
            "is_color":    bool(seq["is_color"]),   # True for RGB (image_2/3), False for gray (image_0/1)
        },
        "SAVE_TRAJECTORY": {
            **_SLAM_IO["SAVE_TRAJECTORY"],
            "basename": f"orb_{seq['test']}_{seq['drive']}",
        },
    }
    CONFIGS_SEQUENCES.mkdir(parents=True, exist_ok=True)
    out = CONFIGS_SEQUENCES / f"{seq['test']}__{seq['drive']}.yaml"
    with out.open("w") as f:
        yaml.dump(cfg, f, default_flow_style=False, sort_keys=False)
    return out


# Main -------------------------------------------------------------------------------------

def main() -> None:
    colour_label = "grayscale" if DATASET_GRAYSCALE else "RGB"
    width_label  = "original" if IMAGE_WIDTH is None else f"{IMAGE_WIDTH}px"
    left_dir     = "image_0" if DATASET_GRAYSCALE else "image_2"
    right_dir    = "image_1" if DATASET_GRAYSCALE else "image_3"

    print("\n=== prep_project.py  —  setting up project ===\n")
    print(f"  KITTI-360 → {colour_label}, {width_label} wide (aspect preserved)")
    print(f"  Layout    → {left_dir}/ (left)  {right_dir}/ (right)  is_color={not DATASET_GRAYSCALE}")
    print(f"  Features  → {NUM_FEATURES}  |  Max depth → {MAX_STEREO_DEPTH}m\n")

    sequences  = []
    kitti_intr = None

    # KITTI-360 ----------------------------------------------------------------------------
    if not RAW_KITTI.exists():
        print(f"  [!] {RAW_KITTI} not found.")
        print(f"      Place KITTI-360 data under dataset/raw/kitti360/")
        return

    print(">>> KITTI-360 ...")

    if RAW_KITTI_CAL.exists():
        print("  - Copying calibration ...")
        shutil.copytree(
            RAW_KITTI_CAL, PROCESSED_CALIB, dirs_exist_ok=True,
            ignore=shutil.ignore_patterns("*:Zone.Identifier", "*.Identifier"),
        )
    else:
        print(f"  [!] Calibration folder not found: {RAW_KITTI_CAL}")

    kitti_intr = _read_kitti_intrinsics(RAW_KITTI_CAL / "perspective.txt")
    if kitti_intr:
        _write_cam_kitti_yaml(CAM_KITTI, kitti_intr, IMAGE_WIDTH, DATASET_GRAYSCALE)
    else:
        print("  [!] cam_kitti360.yaml NOT generated — check perspective.txt")

    test_dirs = sorted(RAW_KITTI_IMG.glob("test_*")) if RAW_KITTI_IMG.exists() else []
    if not test_dirs:
        print(f"  [!] No test_* folders in {RAW_KITTI_IMG}")
    else:
        for test_dir in test_dirs:
            for drive_dir in sorted(d for d in test_dir.iterdir() if d.is_dir()):
                seq = process_sequence(
                    test_dir         = test_dir,
                    drive_dir        = drive_dir,
                    processed_images = PROCESSED_IMAGES,
                    processed_poses  = PROCESSED_POSES,
                    raw_poses_root   = RAW_KITTI_POS,
                    target_width     = IMAGE_WIDTH,
                    grayscale        = DATASET_GRAYSCALE,
                )
                if seq:
                    sequences.append(seq)

    if not sequences:
        print("\n[!] No sequences processed — check raw data paths.")
        return

    # Generate pySLAM sequence configs -----------------------------------------------------
    print("\n>>> Generating sequence configs ...")
    for seq in sequences:
        cfg_path = _generate_sequence_config(seq, CAM_KITTI)
        print(f"  - {cfg_path.relative_to(PC_ROOT)}")

    # Documentation ------------------------------------------------------------------------
    print("\n>>> Writing docs ...")
    DOCS_DATASET.mkdir(parents=True, exist_ok=True)

    resolution = (kitti_intr["w_orig"], kitti_intr["h_orig"]) if kitti_intr else (None, None)
    baseline   = (kitti_intr["bf"] / kitti_intr["fx"])        if kitti_intr else None

    for seq in sequences:
        doc_dir = DOCS_DATASET / seq["test"]
        doc_dir.mkdir(parents=True, exist_ok=True)
        write_sequence_stats(
            doc_dir / "stats.txt",
            seq["test"], seq["drive"],
            seq["frames"], seq["min"], seq["max"],
        )
        if seq["kitti_poses"].is_file():
            plot_trajectory(
                seq["kitti_poses"],
                doc_dir / f"{seq['drive']}_trajectory.png",
                title=f"{seq['test']}  /  {seq['drive']}  [kitti360]",
            )

    plot_dataset_overview(sequences, DOCS_DATASET / "overview.png")
    if resolution[0] and baseline:
        write_dataset_summary(
            DOCS_DATASET / "dataset_summary.txt",
            resolution, baseline, sequences,
        )

    print("\n=== Done. ===\n")
    print(f"  KITTI-360 : {len(sequences)} sequence(s)  "
          f"[{colour_label}, {width_label}, {NUM_FEATURES} features]")
    print(f"\n  Images  → {PROCESSED_IMAGES.relative_to(PC_ROOT)}/  ({left_dir}/ {right_dir}/)")
    print(f"  Poses   → {PROCESSED_POSES.relative_to(PC_ROOT)}/")
    print(f"  Configs → {CONFIGS_SEQUENCES.relative_to(PC_ROOT)}/")
    print(f"  Camera  → src_pc/configs/cam_kitti360.yaml")
    print()
    print("Next step:")
    print("  python3 src_pc/experiments/first_run_pyslam.py\n")


if __name__ == "__main__":
    main()